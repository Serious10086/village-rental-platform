package com.gjf.village.service;

/**
 * 用户行为采集。
 *
 * <h3>这一层的两条硬约束</h3>
 *
 * <p><b>一、它永远不抛异常。</b>采集是旁路 —— 用户来看资源、下单、评价,
 * 这些是主流程;而"记一笔他看过什么"是给推荐用的附加动作。
 * 采集失败(表锁住、字段超长、将来某次改动的副作用)绝不能让主流程失败:
 * 一个用户因为"行为记录写不进去"而下不了单,是荒谬的。
 * 所以每个方法内部把异常全部吞掉并记日志。
 *
 * <p>这不是"静默吞异常"——那种坏味道指的是把错误藏起来让人不知道出了问题。
 * 这里是有意的降级:日志里留了痕,而且就算采集全挂,系统也只是推荐变笨,
 * 功能本身不受影响。<b>旁路就该有旁路的失败姿态。</b>
 *
 * <p><b>二、游客不采集。</b>{@code ai_user_behavior.user_id} 是非空外键,
 * 本来也存不下匿名行为。但更主要的理由是隐私:没登录的人只是在看,
 * 平台没有理由把他的浏览记录下来并据此给他画像。
 * 顺带一个好处是"推荐是登录用户的特权"这件事变得很直白 ——
 * 游客看到的是本村热门,不需要解释为什么推荐变了。
 */
public interface AiBehaviorService {

    /**
     * 记录一次浏览。
     *
     * @param source 来源,取值见 {@code AiUserBehavior.SOURCE_*}。
     *               推荐位那次点击必须传 {@code SOURCE_RECOMMEND},
     *               后台的点击率统计就认它
     */
    void viewed(Long resourceId, Integer staySeconds, int source);

    /** 记录一次搜索。搜索的目标是一个词,没有资源 id */
    void searched(String keyword);

    void favorited(Long resourceId);

    void ordered(Long resourceId);

    void evaluated(Long resourceId);

    /**
     * 记录一次推荐位曝光(推荐接口每次返回结果时调用一次)。
     *
     * <p><b>它是点击率的分母。</b>没有这一条,后台只能报一个光秃秃的点击数,
     * 那个数字说明不了任何事 —— 一天 50 次点击是多还是少?
     *
     * <p>一次请求记<b>一行</b>,不是每个卡片一行:同一时刻同一个推荐位上的
     * 十几个卡片,信息量是一样的。代价是算不出单卡的曝光数,
     * 但这一批不需要那个粒度。
     *
     * <p>游客不记(和上面几个方法一样)—— 于是点击率统计的分母
     * 天然只含登录用户。这一点在后台页面上要说明,不然那个数会被人
     * 当成"全站点击率"。
     */
    void impression();
}
