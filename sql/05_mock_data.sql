SET NAMES utf8mb4;
USE `village_rental`;

-- 清空(注意顺序:依赖资源的表要先清)
--
-- 【为什么 msg_conversation 必须排在 biz_order 前面】
-- msg_conversation.order_id 是指向 biz_order 的外键(RESTRICT)。
-- 这里恰好是一个"看起来无关"的依赖:会话表在概念上属于互动域,
-- 订单表属于交易域,凭直觉不会想到要按先后顺序删 ——
-- 而它是一个真实存在的外键,顺序错了整段脚本从中间断掉,
-- 后面的重置自增、演示数据全部不执行,库却停在半清空的状态。
DELETE FROM `biz_credit_record`;
DELETE FROM `biz_evaluation`;
DELETE FROM `biz_payment`;
DELETE FROM `biz_dispute`;
DELETE FROM `biz_withdraw`;
DELETE FROM `msg_chat_message`;
DELETE FROM `msg_conversation`;
DELETE FROM `biz_order`;
DELETE FROM `msg_notice`;
DELETE FROM `biz_board_like`;
-- 留言板:self-FK fk_board_parent 是 ON DELETE RESTRICT,一次 DELETE 清不掉。
--
-- 回复的 parent_id 指向主帖,删父行之前必须先删子行。写一条
-- DELETE FROM biz_board 的话,MySQL 按自己的顺序逐行删,一旦先删到
-- 某条主帖(它的回复还在),整条语句直接报 1451 中断 ——
-- 而中断点在文件前段,后面的重置自增和全部演示数据都不会执行,
-- 库停在"留言清了一半、公告还是上一轮的"这种状态。
-- 所以这里必须分成两条,先回复后主帖。
DELETE FROM `biz_board` WHERE `parent_id` IS NOT NULL;
DELETE FROM `biz_board` WHERE `parent_id` IS NULL;
-- 公告:发布人是指向 sys_user 的外键(RESTRICT),所以必须排在
-- 下面那段删用户的 SQL 之前。漏掉这一条的话,第一次跑没事,
-- 第二次跑就会因为"演示公告还挂在上一个演示账号上"而卡住。
DELETE FROM `biz_announcement`;
DELETE FROM `ai_user_behavior`;
-- AI 对话记录:和 biz_announcement 同一个道理 —— 它也有指向 sys_user 的外键
-- (fk_aichat_user,RESTRICT),必须排在删用户的 SQL 之前。
--
-- 漏掉它的后果不只是"删不掉用户",还有更隐蔽的一层:这张表是**只增不改**的,
-- 不清的话每跑一轮接口测试就多几条记录,后台的降级率跟着一轮一个数,
-- 断言就再也写不成绝对值了。
DELETE FROM `ai_chat_record`;
-- 操作日志:和 ai_chat_record 完全同一个道理,而且是**批次 9 补上的** ——
-- 这张表也是只增不改,每跑一轮接口测试/E2E 就多几十上百条。
-- 不清的后果在批次 9 真的发生了:统计那套接口测试里有一条断言是
-- "按日期筛今天能查到今天的日志",它的隐含前提是"库里只有今天的日志" ——
-- 结果库里躺着前一天跑测试留下的 25 条,断言第二天就自己坏了。
--
-- (那条断言本身也修了,见 scripts/api_test_stat.py:日期改成算出来的。
--  但清理这一行仍然要对:让"重置演示数据"真的回到一个已知状态,
--  是这份脚本存在的意义 —— 补一个断言不如让前提成立。)
DELETE FROM `sys_operation_log`;
-- 审核流水:资源类(2)、实名类(1)和外来用户备案类(3)都要清,否则重跑会堆积
DELETE FROM `sys_audit_record` WHERE `biz_type` IN (1, 2, 3);
-- 资源收藏:指向 biz_resource 的外键是 RESTRICT,不清的话下面那行删资源
-- 会被它挡住(报 ERROR 1451)。这已经是第三次踩同一类坑了 ——
-- **每加一张表,都要检查三处:建表脚本的 DROP 列表、这里的清理列表、
-- 以及和已有表的外键顺序。** 漏掉任何一处,报错都出现在看上去无关的地方。
DELETE FROM `biz_resource_favorite`;
DELETE FROM `biz_resource`;

-- 清理测试过程中注册的临时账号。
--
-- 接口测试脚本会用随机号段注册新用户来验证"注册 → 实名 → 审核"闭环
-- (api_test.py 用 139 号段,api_test_audit.py 用 137 号段),
-- 每跑一轮就多出几个"测试用户"。
--
-- 【为什么用白名单而不是按号段删】
-- 按 137/139 号段删的话,测试脚本哪天换个号段(或者再加一个脚本),
-- 漏网账号就会继续累积 —— 积累到把演示账号挤出后台列表第一页,
-- 演示时看起来像数据被污染了。按"只保留演示账号"来删,
-- 无论测试用哪个号段都不会漏。
--
-- 顺序不能变:先删审核流水,再删用户角色关联,最后删用户 ——
-- 外键是 RESTRICT,顺序错了会删不掉。
DELETE FROM `sys_audit_record` WHERE `applicant_id` NOT IN
    (SELECT `id` FROM (SELECT `id` FROM `sys_user` WHERE `phone` LIKE '138000000%') AS keep);
DELETE FROM `sys_user_role` WHERE `user_id` NOT IN
    (SELECT `id` FROM (SELECT `id` FROM `sys_user` WHERE `phone` LIKE '138000000%') AS keep);
DELETE FROM `sys_user` WHERE `phone` NOT LIKE '138000000%';

-- 重置自增计数器。
