-- ============================================================================
--  一致性校验 —— 跑完脚本务必看这几行
--
--  下面每一条查询的期望值都写在列名里。只要出现 0 行或数字对不上,
--  就说明订单、资金、信用、资源四者之间已经脱节,
--  演示时会出现"有订单却查不到流水""资源在交易中却还能下单"这类怪象。
-- ============================================================================

-- ① 订单状态分布(期望:待确认 1 / 待付款 1 / 待交付 1 / 使用中 1 /
--    已完成 3 / 已取消 1 / 已拒绝 1 / 纠纷中 1)
SELECT '① 订单状态分布' AS 校验项, `order_status` AS 状态,
       CASE `order_status`
           WHEN 0 THEN '待卖家确认' WHEN 1 THEN '待付款' WHEN 2 THEN '待交付'
           WHEN 3 THEN '使用中' WHEN 4 THEN '已完成' WHEN 5 THEN '已取消'
           WHEN 6 THEN '纠纷中' WHEN 7 THEN '卖家已拒绝' END AS 含义,
       COUNT(*) AS 单数
FROM `biz_order` GROUP BY `order_status` ORDER BY `order_status`;

-- ② 每笔已支付订单都必须有"买家付款 + 卖家结算"两条流水
--    (期望:0 行。有行说明有笔付款没记账)
SELECT '② 缺流水的已支付订单' AS 校验项, o.`order_no`, o.`pay_amount`
FROM `biz_order` o
WHERE o.`pay_status` = 1
  AND (SELECT COUNT(*) FROM `biz_payment` p
        WHERE p.`order_id` = o.`id` AND p.`pay_type` = 1) = 0;

-- ③ 信用分流水必须首尾相接,且终点等于用户当前分数
--    (期望:0 行)
SELECT '③ 信用分对不上的用户' AS 校验项, u.`id`, u.`real_name`,
       u.`credit_score` AS 用户当前分, x.`last_score` AS 流水终点
FROM `sys_user` u
JOIN (SELECT `user_id`, MAX(`after_score`) AS `last_score`
      FROM `biz_credit_record` GROUP BY `user_id`) x ON x.`user_id` = u.`id`
WHERE u.`credit_score` <> x.`last_score`;

-- ④ 出售类资源的锁定状态必须与订单一致
--    (未完结 → 交易中;已完成 → 已完成。期望:0 行)
SELECT '④ 出售类资源状态与订单脱节' AS 校验项, o.`order_no`,
       o.`order_status` AS 订单状态, r.`resource_status` AS 资源状态
FROM `biz_order` o JOIN `biz_resource` r ON r.`id` = o.`resource_id`
WHERE o.`order_type` = 2
  AND ((o.`order_status` IN (0, 1, 2, 3) AND r.`resource_status` <> 3)
    OR (o.`order_status` = 4 AND r.`resource_status` <> 4));

-- ⑤ 余额必须等于「结算流水合计」减去「已占用在提现里的钱」
--    (期望:0 行)
--
--    提现是<b>申请时就扣款</b>的,所以要从余额里减掉;但只减待审核(0)
--    和已打款(1)的 —— 已驳回(2)的那笔钱已经退回余额了,再减一次
--    等于同一笔钱扣了两遍。
--    status IN (0,1) 这个口径必须和 WalletServiceImpl 里的
--    STATUS_COUNTED_AS_WITHDRAWN 一致,改一处就要改另一处。
SELECT '⑤ 余额与流水对不上' AS 校验项, u.`id`, u.`real_name`,
       u.`balance` AS 余额,
       IFNULL((SELECT SUM(p.`amount`) FROM `biz_payment` p
               WHERE p.`user_id` = u.`id` AND p.`pay_type` = 4), 0) AS 结算合计,
       IFNULL((SELECT SUM(w.`amount`) FROM `biz_withdraw` w
               WHERE w.`user_id` = u.`id` AND w.`status` IN (0, 1)), 0) AS 提现占用
FROM `sys_user` u
WHERE u.`balance` <> IFNULL((SELECT SUM(p.`amount`) FROM `biz_payment` p
                             WHERE p.`user_id` = u.`id` AND p.`pay_type` = 4), 0)
                  - IFNULL((SELECT SUM(w.`amount`) FROM `biz_withdraw` w
                            WHERE w.`user_id` = u.`id` AND w.`status` IN (0, 1)), 0);

-- ⑥ 评价必须挂在已完成的订单上
