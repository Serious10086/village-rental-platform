   OR (w.`status` <> 0 AND (w.`audit_user_id` IS NULL OR w.`audit_time` IS NULL))
   OR (w.`status` = 1 AND w.`finish_time` IS NULL)
   OR (w.`status` = 2 AND w.`finish_time` IS NOT NULL);

-- ⑩ 每条聊天消息的双方,都必须是这条会话的参与人(期望:0 行)
