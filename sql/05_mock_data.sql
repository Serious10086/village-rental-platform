       m.`conversation_id`, m.`from_user_id`, m.`to_user_id`,
       c.`user_a_id`, c.`user_b_id`
FROM `msg_chat_message` m JOIN `msg_conversation` c ON c.`id` = m.`conversation_id`
WHERE m.`from_user_id` NOT IN (c.`user_a_id`, c.`user_b_id`)
   OR m.`to_user_id` NOT IN (c.`user_a_id`, c.`user_b_id`)
   OR m.`from_user_id` = m.`to_user_id`;

-- ⑪ 会话的未读数必须等于该收件人实际的未读消息条数(期望:0 行)
--    a_unread / b_unread 是冗余列(每次发消息在数据库端自增)。
--    对不上的表现很直观:消息列表上有红点,点进去一条未读都没有,
--    或者读完了红点还在。冗余列的代价就是必须有人校验它。
SELECT '⑪ 会话未读数与消息对不上' AS 校验项, c.`id` AS 会话ID,
       c.`a_unread` AS a未读,
       (SELECT COUNT(*) FROM `msg_chat_message` m
         WHERE m.`conversation_id` = c.`id`
           AND m.`to_user_id` = c.`user_a_id` AND m.`is_read` = 0) AS a实际,
       c.`b_unread` AS b未读,
       (SELECT COUNT(*) FROM `msg_chat_message` m
         WHERE m.`conversation_id` = c.`id`
           AND m.`to_user_id` = c.`user_b_id` AND m.`is_read` = 0) AS b实际
FROM `msg_conversation` c
WHERE c.`a_unread` <> (SELECT COUNT(*) FROM `msg_chat_message` m
                       WHERE m.`conversation_id` = c.`id`
                         AND m.`to_user_id` = c.`user_a_id` AND m.`is_read` = 0)
   OR c.`b_unread` <> (SELECT COUNT(*) FROM `msg_chat_message` m
                       WHERE m.`conversation_id` = c.`id`
                         AND m.`to_user_id` = c.`user_b_id` AND m.`is_read` = 0);

-- ⑫ 留言板的冗余计数必须与明细对得上(期望:0 行)
--    reply_count / like_count 是冗余列,值由业务代码在发帖、回复、点赞时维护。
--    对不上的表现很直观:帖子上写着"3 条回复",点开只有 2 条;或者有人
--    回复了数字却不动。这两个数字是用户判断"这条留言热不热闹"的唯一依据,
--    错了比不显示更糟。
--
--    两个容易漏的点:
--      · 子回复也要算进 reply_count —— 判断条件是 parent_id 指向本行,
--        而不是"本行的 parent_id 为空"
--      · 逻辑删除的回复不算 —— 所以子查询要带 deleted = 0,
--        数上了会得到一个永远减不掉的虚高数字
SELECT '⑫ 留言计数与明细对不上' AS 校验项, b.`id` AS 留言ID,
       LEFT(b.`content`, 20) AS 内容摘要,
       b.`reply_count` AS 记录回复数,
       (SELECT COUNT(*) FROM `biz_board` r
         WHERE r.`parent_id` = b.`id` AND r.`deleted` = 0) AS 实际回复数,
       b.`like_count` AS 记录点赞数,
       (SELECT COUNT(*) FROM `biz_board_like` l WHERE l.`board_id` = b.`id`) AS 实际点赞数
FROM `biz_board` b
WHERE b.`deleted` = 0
  AND (b.`reply_count` <> (SELECT COUNT(*) FROM `biz_board` r
                            WHERE r.`parent_id` = b.`id` AND r.`deleted` = 0)
    OR b.`like_count` <> (SELECT COUNT(*) FROM `biz_board_like` l
                           WHERE l.`board_id` = b.`id`));



-- ⑬ AI 对话记录的状态与字段对不上(期望:0 行)
--    status 是这一批的核心字段,它和另外几列之间有硬性对应关系:
--      · 成功(1) 必须没有降级原因 —— 有原因说明"成功了但也被降级了",
--        这是自相矛盾的,只可能是写记录的那段代码出了错
--      · 降级(2) 和失败(3) 必须填了原因 —— 没有原因的话,后台的
--        "原因分布"会有一根没有名字的柱子,排查时根本不知道该查什么
--      · 失败(3) 必须是"没调用" —— 它代表提问被内容安全拦下,
--        压根没往外发,所以不可能消耗 token。有 token 说明它其实发了出去,
--        那"拦截不花钱"这个说法就是假的
SELECT '⑬ AI记录状态与字段矛盾' AS 校验项, a.`id` AS 记录ID,
       a.`status` AS 状态, a.`degrade_reason` AS 降级原因,
       CONCAT(a.`prompt_tokens`, '+', a.`completion_tokens`) AS tokens,
       LEFT(a.`question`, 20) AS 提问摘要
FROM `ai_chat_record` a
WHERE (a.`status` = 1 AND a.`degrade_reason` IS NOT NULL)
   OR (a.`status` <> 1 AND a.`degrade_reason` IS NULL)
   OR (a.`status` = 3 AND (a.`prompt_tokens` <> 0 OR a.`completion_tokens` <> 0));

