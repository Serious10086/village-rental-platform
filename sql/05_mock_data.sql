--    三个不变量:
--      · 有未决纠纷(status 0/1)的订单必须挂在"纠纷中"(6)——
--        否则订单会绕过调解继续往下走,纠纷还在,货已经交付了
--      · 已结束的纠纷必须有人处理过(handler_id 非空)——
--        空着说明这条记录不知道自己是怎么结束的
--      · order_status_before 只能是 2 或 3 ——
--        申请纠纷的入口就卡这两个状态,存出别的值说明有代码绕过了校验
SELECT '⑧ 未决纠纷与订单状态脱节' AS 校验项, d.`dispute_no`,
