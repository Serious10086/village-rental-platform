--   · 状态以"已上架(1)"为主,另留几条其他状态用于演示后台审核和"我的发布"
--   · risk_level 按分类继承(电力设备=3 高风险,会自动带出"需培训")
--   · 图片用前端 public/demo 下的示意图,不依赖外部图床 ——
