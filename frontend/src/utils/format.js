/**
 * 展示层格式化工具。
 *
 * 【为什么需要一个 formatDateTime】
 * 后端返回的时间是 ISO 格式(2026-09-16T10:00:00),直接绑到模板上
 * 会带着一个 T 显示,看起来像没做完的东西。这个问题原本在
 * 通知页和资源详情页各写了一遍,到了评价和信用页又要再写两遍 ——
 * 重复到第 4 处就该抽出来,而不是继续复制。
 */

/**
 * 把 ISO 时间格式化成"2026-09-16 10:00"。
 *
 * <p>只截到分钟:秒对用户没有意义,反而占地方。
 * 精确到秒的场景(比如排查问题)应当看接口返回的原始值。
 */
export function formatDateTime(value) {
  if (!value) {
    return ''
  }
  return String(value).replace('T', ' ').slice(0, 16)
}

/**
 * 只要"10:00"这样的小时分钟。
 *
 * <p>订单时间轴用它 —— 五个节点挤在一列里,每个都带完整日期会
 * 把时间轴撑得很长,而它们通常发生在同几天内,日期是冗余信息。
 */
export function formatTimeOnly(value) {
  if (!value) {
    return ''
  }
  const s = String(value).replace('T', ' ')
  return s.length >= 16 ? s.slice(11, 16) : s
}

/** 日期部分:"2026-09-16" */
export function formatDateOnly(value) {
  if (!value) {
    return ''
  }
  return String(value).slice(0, 10)
}

/**
 * 金额统一两位小数:4240 → "4240.00"。
 *
 * <p>【为什么这件事必须由一个函数来做】
 * 后端返回的是 `BigDecimal("4240.00")`,但 JSON 往返一趟就变成了 JS 数字
 * `4240` —— 小数点后的零在类型转换里丢掉了。于是同一笔钱在订单页显示
 * `¥4240`、在下单确认页(那里提前用 `toFixed(2)` 算过)显示 `¥4240.00`,
 * 两个页面对不上。这不是"少显示两位",是**看起来像两笔不同的钱**。
 *
 * <p>【返回的是数字串,不带 ¥】
 * 各处 ¥ 的位置和所在容器都不一样(有的在 span 里,有的在模板字符串里),
 * 把它塞进这个函数反而要在调用处拆开。函数只管数字,符号留在原处。
 *
 * <p>【不用 toLocaleString 加千分位】
 * 全站只有资源价格那一处加过千分位,其余都是裸数字。要让显示一致,
 * 只能"全都加"或"全都不加";加千分位是比"补两位小数"大得多的视觉改动,
 * 而这一批的目标只是后者。数字超过万位时读起来确实不如千分位,
 * 真要改应当全站一起决定,而不是在这一处留下例外。
 *
 * <p>【非数字返回 "0.00" 而不是 "NaN"】
 * 正常情况下不会走到这里。但万一走到,屏幕上出现 `¥NaN` 比出现
 * `¥0.00` 更糟 —— 前者是崩溃的样子,后者最差只是数字不对,
 * 而且下一笔正常的金额会把它覆盖掉。
 */
export function formatMoney(value) {
  if (value === null || value === undefined || value === '') {
    return '0.00'
  }
  const n = Number(value)
  return Number.isFinite(n) ? n.toFixed(2) : '0.00'
}
